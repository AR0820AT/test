/** 500 个高频词，按常用度排序 */
export const TOP_WORDS: WordEntry[] = RAW.trim()
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [word, pos] = line.split('|')
    return { word, pos: (pos || 'noun') as WordPos }
  })

